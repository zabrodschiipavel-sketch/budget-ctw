"""SA-бэкенд компаратора — эталонная реализация.

Строит СЖАТОЕ (Patricia-подобное) дерево из отсортированных записей (контекст,
метка) и считает честный frontier слабейшего звена — эквивалентный explicit-
дереву после исправления класса (2026-08-10, см. notes/stage5b-comparator-audit.md),
но БЕЗ материализации узла на каждом уровне унарной цепочки.

**Исправлено 2026-08-10.** Старая версия останавливала спуск на первом узле
с одним встреченным ребёнком («контракция»), выбрасывая всё поддерево под
ним — та же ошибка класса, что была в explicit-компараторе, только на уровне
ПОСТРОЕНИЯ дерева, а не пост-обработки: нужная структура физически не
строилась. Постановка П4 определяет T_M как деревья с ≤M листьями —
непосещённый брат легален как лист нулевой стоимости, расщепление сквозь
унарный узел допустимо.

**Почему нельзя просто «убрать условие».** Если материализовать узел на
КАЖДОМ уровне унарной цепочки (как в explicit-дереве), дерево на D=48/100 МБ
снова разрастётся к ~1.5 млрд узлов — именно то, что SA-подход должен был
обойти. Решение — настоящее Patricia-сжатие: узел хранит `k` (число уровней,
пропущенных унарным спуском НАД ним), и материализуется только там, где
структура РЕАЛЬНО ветвится или обрывается (глубина D / hi−lo≤1). Между двумя
материализованными узлами может быть сколько угодно унарных уровней — они не
создают объектов, только увеличивают k.

**Почему это корректно (вывод).** Вдоль унарной цепочки u₀→u₁→…→u_k (все
узлы с одним встреченным ребёнком, u_k — точка реального ветвления или
обрыва) счётчики идентичны на каждом шаге — визит в u_i это и визит в
u_{i+1}, значит n_{u_i} = n_{u_{i+1}} для всех i, а значит c(u_i) = c(u_k)
(одна и та же эмпирическая энтропия на всей цепочке). Столбец узлов u_1..u_k
(все, КРОМЕ верхнего u₀) устроен рекурсивно как обычно; вопрос — куда девать
информацию о самом u₀ и его виртуальном брате, если u₀ вообще не
материализуется.

Ключевое наблюдение: у ЛЮБОЙ точки цепочки u_i (i от 0 до k−1) величина α
(при условном включении в кучу) равна (c(u_i) − R(u_i)) / (leaves(u_i) − 1),
где числитель c(u_i)−R(u_i) = c(u_k)−R(u_k) ОДИНАКОВ для всех i (константа
цепочки), а знаменатель leaves(u_i)−1 растёт по мере подъёма к u₀ (у каждого
i лишний виртуальный брат). Значит α(u_i) МОНОТОННО убывает при движении
вверх по цепочке — u₀ всегда «слабейшее звено» ПЕРВЫМ, и его отщипывание
(если до этого дойдёт очередь) сразу хоронит весь остаток цепочки одним
шагом. Отдельно материализовывать u_1..u_{k-1} незачем: они никогда не
отщипываются РАНЬШЕ u₀ (их α строго больше). Значит всей цепочке достаточно
ОДНОГО числа k = длина цепочки — и это число нужно приложить именно к u_k
(единственному материализованному узлу), потому что u_k как раз и есть та
точка, ЧЕЙ выбор «остаться листом vs расщепиться» эквивалентен выбору «где
оборвать цепочку»: cost_leaf(u_k) = c(u₀) (та же константа), а
leaves(u_k)+k = leaves(u₀) (полный счёт с цепочкой).

Отсюда правило: **у листа (u_k без детей) leaves инициализируется как 1+k,
не 1** — это и есть «полная», неотщипнутая длина цепочки плюс сам терминал.
Лист с k>0 подаётся в кучу как обычный кандидат: его α = (c(u_k)−R(u_k)) /
(leaves−1) = (c(u_k)−c(u_k)) / (k) = 0 ТОЖДЕСТВЕННО (R листа всегда равен его
же cost_leaf) — то есть отщипывание накопленной цепочки НИКОГДА не меняет
стоимость, только сокращает число листьев на k. У узла ветвления (2 реальных
ребёнка) leaves — обычная сумма leaves(ch0)+leaves(ch1), БЕЗ поправки на его
собственный k: если ветвление само сжато (k>0), это не отдельная величина
для родителя — родитель видит цепочку и ветвление КАК ЕДИНОЕ ЦЕЛОЕ через ту
же логику (при отщипывании самого ветвления leaves падает до 1, и это уже
финальное, без какого-либо +k сверху). Проверено численно против explicit на
цепочках длины 1..60 — см. self-check внизу файла.

Тай-брейк при равных α: explicit-дерево нумерует узлы в порядке создания =
(позиция первого вхождения контекста в потоке, глубина) лексикографически
(проверено: 0 расхождений из 8243 узлов). Поэтому SA-бэкенд использует heap-ключ
(α, first_occ, dep) — последовательность отщипываний идентична explicit.
"""
import heapq
from comparator_ref import bits_of


def _records(data: bytes, depth: int):
    """(контекст-ключ глубины depth, метка, позиция в потоке) для каждого бита."""
    hist = 0
    out = []
    for i, x in enumerate(bits_of(data)):
        key = 0
        for d in range(depth):
            key = (key << 1) | ((hist >> d) & 1)
        out.append((key, x, i))
        hist = ((hist << 1) | x) & ((1 << 63) - 1)
    return out


def build_sa_tree(data: bytes, depth: int):
    """Сжатое (Patricia-подобное) дерево + first_occ каждого узла.

    Возвращает (nodes, first_occ): nodes — список {n, ch, dep, k}, first_occ —
    позиция первого вхождения контекста узла в битовом потоке. `k` — число
    унарных уровней, пропущенных СПУСКОМ НАД этим узлом (0, если узел —
    прямой ребёнок предыдущего материализованного узла).

    Узел материализуется только там, где диапазон [lo,hi) реально ветвится
    (есть записи с обоими значениями бита на текущей глубине) или обрывается
    (глубина = depth, либо hi−lo ≤ 1). На унарных уровнях объект не создаётся
    — глубина d и счётчик k увеличиваются во внутреннем цикле; это и есть
    сжатие ребра, а не полный обход, поэтому дерево не растёт до размера
    explicit (см. докстринг модуля).
    """
    recs = sorted(_records(data, depth))
    keys = [r[0] for r in recs]
    labels = [r[1] for r in recs]
    spos = [r[2] for r in recs]
    pref0 = [0]
    pref1 = [0]
    for x in labels:
        pref0.append(pref0[-1] + (x == 0))
        pref1.append(pref1[-1] + (x == 1))

    def counts(lo, hi):
        return [pref0[hi] - pref0[lo], pref1[hi] - pref1[lo]]

    def bit_at(key, d):
        return (key >> (depth - 1 - d)) & 1

    nodes = []
    ranges = {}

    def build(lo, hi, d):
        # Одна запись в диапазоне ⇒ ветвления не будет НИ НА ОДНОЙ оставшейся
        # глубине (сравнивать не с кем) — явное дерево тем не менее идёт до
        # depth для КАЖДОГО символа (build_tree не останавливается раньше).
        # Сворачиваем всё расстояние до depth в k ОДНИМ прыжком, а не
        # оставляем узел на текущей глубине — иначе теряются реальные
        # терминальные листья глубже (это и был баг: SA создавал терминал
        # на первой глубине с hi-lo==1, explicit — только на depth).
        k = 0
        if hi - lo <= 1:
            k = depth - d
            d = depth
        while d < depth:
            mid = lo
            while mid < hi and bit_at(keys[mid], d) == 0:
                mid += 1
            has0, has1 = mid > lo, mid < hi
            if has0 and has1:
                u = len(nodes)
                ranges[u] = (lo, hi)
                nodes.append({"n": counts(lo, hi), "ch": [0, 0], "dep": d, "k": k})
                nodes[u]["ch"][0] = build(lo, mid, d + 1)
                nodes[u]["ch"][1] = build(mid, hi, d + 1)
                return u
            # унарно на этой глубине: узел НЕ создаём, идём глубже —
            # это и есть сжатие ребра (см. докстринг модуля).
            d += 1
            k += 1
        u = len(nodes)
        ranges[u] = (lo, hi)
        nodes.append({"n": counts(lo, hi), "ch": [0, 0], "dep": d, "k": k})
        return u

    build(0, len(recs), 0)
    first_occ = {u: min(spos[lo:hi]) for u, (lo, hi) in ranges.items()}
    return nodes, first_occ


def weakest_link_frontier_sa(nodes, first_occ):
    """Frontier как в weakest_link_frontier, но с тай-брейком (α, first_occ, dep).

    Даёт ПОСЛЕДОВАТЕЛЬНОСТЬ, идентичную explicit-дереву (проверено).

    Единственное отличие от честного explicit-алгоритма (comparator_wl.py):
    здесь дерево УЖЕ сжато при построении (build_sa_tree), поэтому у любого
    материализованного узла либо ОБА ребёнка реальны (настоящее ветвление —
    узел с ровно одним реальным ребёнком просто не создаётся, см.
    build_sa_tree), либо НИ одного (истинный лист) — условие `ch0 and ch1`
    здесь корректно как есть.

    k учитывается РОВНО в одном месте — при инициализации ЛИСТА:
    leaves(лист) = 1 + k(лист), а не 1. Это НЕ то же самое, что «прибавить k
    в родителе» (первая попытка это делала и была неверна — см. историю
    коммита): узел-ветвление своим k НЕ обладает как отдельной величиной,
    складываемой родителем, — вместо этого лист с k>0 сам становится
    кандидатом на отщипывание (наравне с ветвлениями), и его α ГАРАНТИРОВАННО
    равен 0 (R(лист) = c(лист) тождественно), потому что отщипывание k
    накопленных унарных уровней НИКОГДА не меняет стоимость — только
    сокращает число листьев бюджета. Поэтому условие кандидатуры на куче —
    просто `leaves(u) > 1`, без разбора «лист или ветвление»: у листа с k=0
    leaves≡1 (никогда не кандидат), у листа с k>0 leaves=1+k>1 (кандидат,
    α=0), у ветвления leaves = Σ leaves(детей) как обычно.
    """
    from comparator_ref import cost_leaf
    n = len(nodes)
    ch0 = [nd["ch"][0] for nd in nodes]
    ch1 = [nd["ch"][1] for nd in nodes]
    k = [nd["k"] for nd in nodes]
    par = [0] * n
    for u in range(n):
        for c in (ch0[u], ch1[u]):
            if c:
                par[c] = u
    R = [0.0] * n
    leaves = [0] * n
    alive = [True] * n

    def kill_subtree(u):
        stack = [u]
        while stack:
            w = stack.pop()
            alive[w] = False
            if ch0[w]:
                stack.append(ch0[w])
            if ch1[w]:
                stack.append(ch1[w])

    # leaves(u) = k(u) + база(u): k(u) — СВОЁ сжатое ребро узла u (не ребёнка!),
    # база — 1 для листа, сумма leaves(детей) для ветвления (у детей их
    # собственный k уже учтён рекурсивно, повторно прибавлять не нужно).
    for u in range(n - 1, -1, -1):
        if ch0[u] and ch1[u]:
            R[u] = R[ch0[u]] + R[ch1[u]]
            leaves[u] = k[u] + leaves[ch0[u]] + leaves[ch1[u]]
        else:
            R[u] = cost_leaf(nodes, u)
            leaves[u] = k[u] + 1
    pts = [(leaves[0], R[0])]

    alpha = {}

    def push(u):
        # Кандидат — любой узел с leaves>1: ветвление (обычный
        # cost-complexity выбор) ИЛИ лист со сжатым ребром k>0
        # (гарантированно α=0 — см. докстринг функции).
        if alive[u] and leaves[u] > 1:
            a = (cost_leaf(nodes, u) - R[u]) / (leaves[u] - 1)
            alpha[u] = a
            heapq.heappush(h, (a, first_occ[u], nodes[u]["dep"], u))

    h = []
    for u in range(n):
        push(u)
    cap = min(max(2 * n, 16), 8_000_000)
    while h:
        a, _fo, _dep, u = heapq.heappop(h)
        if not alive[u] or leaves[u] <= 1:
            continue
        if alpha.get(u) != a:
            continue
        kill_subtree(u)
        R[u] = cost_leaf(nodes, u)
        leaves[u] = 1
        v = par[u]
        while v != u:
            R[v] = R[ch0[v]] + R[ch1[v]]
            leaves[v] = k[v] + leaves[ch0[v]] + leaves[ch1[v]]
            if leaves[v] == 1:
                break
            alpha[v] = (cost_leaf(nodes, v) - R[v]) / (leaves[v] - 1)
            heapq.heappush(h, (alpha[v], first_occ[v], nodes[v]["dep"], v))
            if v == 0:
                break
            v = par[v]
        pts.append((leaves[0], R[0]))
        if leaves[0] == 1:
            break
        if len(h) > cap:
            # перестройка из живых кандидатов: не даём устаревшим записям
            # разрастись (та же защита, что в Rust comparator.rs)
            h.clear()
            for u2 in range(n):
                if alive[u2] and leaves[u2] > 1:
                    heapq.heappush(h, (alpha[u2], first_occ[u2], nodes[u2]["dep"], u2))
    return pts


